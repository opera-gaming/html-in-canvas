// Footer tiles are measured on the dark footer background, so their opacity
// is derived from how far each colour sits from that background.
const FOOTER_BG = { r: 14, g: 14, b: 12 };

export const FOOTER_WHEEL: WheelGeometry = {
  width: VIEWBOX_WIDTH,
  height: VIEWBOX_HEIGHT,
  radius: 0.2,
  tiles: WHEEL_TILES.map(([x, y, w, h, r, g, b]) => {
    const dist = Math.abs(r - FOOTER_BG.r) + Math.abs(g - FOOTER_BG.g) + Math.abs(b - FOOTER_BG.b);
    const opacity = Math.max(0.12, Math.min(1, dist / 260));
    return [x, y, w, h, `rgb(${r},${g},${b})`, Number(opacity.toFixed(2))] as const;
  }),
};
