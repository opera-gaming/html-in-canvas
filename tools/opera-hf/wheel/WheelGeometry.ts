// Tile positions/sizes/colors are baked directly from pixel measurements of
// the reference design (connected-component analysis of the Figma footer
// screenshot) — not a procedural/parametric approximation. Each row is
// [x, y, w, h, r, g, b] in the shared viewBox below. This table MUST stay in
// sync with the inline SVG in includes/footer/tabscape-wheel.html — both are
// generated from the same source measurement, so the no-JS baseline and the
// canvas hover layer paint the exact same picture.

// [cx, cy, w, h, color, opacity?] — opacity defaults to 1.
