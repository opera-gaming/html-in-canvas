// Shared by import-transitions.mjs: upstream credits per transition and the generated module's text.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

// Prefab ids whose upstream file name differs by more than case and separators.
const ALIASES = {
  bowtie: 'BowTieHorizontal',
  caleidoscope: 'kaleidoscope',
  crazy_parametric: 'CrazyParametricFun',
  doom: 'DoomScreenTransition',
  flye_eye: 'flyeye',
  leaf: 'LeftRight',
  rotate_scale_face: 'rotate_scale_fade',
  butterfly_wave: 'ButterflyWaveScrawler',
  color_distance: 'ColourDistance',
};

const normalise = (name) => name.toLowerCase().replace(/[^a-z0-9]/g, '');

/** Returns a function mapping a prefab transition id to `{ file, author, license }`; throws if it has no match. */
export function creditsFrom(glTransitionsDir) {
  const dir = join(glTransitionsDir, 'transitions');
  const files = new Map(
    readdirSync(dir)
      .filter((f) => f.endsWith('.glsl'))
      .map((f) => [normalise(f.slice(0, -5)), f]),
  );
  return (id) => {
    const file = files.get(normalise(ALIASES[id] ?? id));
    if (!file) throw new Error(`no gl-transitions shader for ${id}`);
    const src = readFileSync(join(dir, file), 'utf8');
    const field = (key) => new RegExp(`^//\\s*${key}:\\s*(.+?)\\s*$`, 'm').exec(src)?.[1];
    const author = field('Author')?.replace(/\s*<[^>]*>/, '');
    const license = field('License');
    if (!author || !license) throw new Error(`${file} has no Author/License header`);
    return { file, author, license };
  };
}

